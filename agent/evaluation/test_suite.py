"""Fixed test-instance materialization for Phase K and later experiments."""

from __future__ import annotations

import csv
from dataclasses import dataclass
from pathlib import Path

import numpy as np

from data.generator import InstanceGenerator, load_parameter_table
from data.io import load_instance_csv, save_instance_csv


TEST_INDEX_FIELDS = [
    "instance_id", "relative_path", "scale", "scenario", "generation_seed",
    "target_load_ratio", "due_tightness", "num_orders", "num_cells",
    "num_workers", "num_robots", "num_stages", "num_products",
    "relocation_multiplier", "worker_skill_density", "robot_capability_density",
    # Paper-facing structural symbols. ``A`` is retained as a deprecated
    # compatibility column for indexes generated by older releases.
    "S", "M", "A", "J", "H", "R", "V", "parameter_case_id",
]


@dataclass(frozen=True, slots=True)
class TestRecord:
    __test__ = False
    instance_id: str
    path: str
    scale: str
    scenario: str
    generation_seed: int
    target_load_ratio: float
    due_tightness: str
    parameter_case_id: str | None = None
    num_cells: int | None = None
    num_stages: int | None = None
    num_robots: int | None = None
    num_orders: int | None = None
    relocation_multiplier: float = 1.0
    worker_skill_density: float | None = None
    robot_capability_density: float | None = None


def _seed(base_seed: int, combo: int, rep: int) -> int:
    seq = np.random.SeedSequence([int(base_seed), int(combo), int(rep)])
    return int(seq.generate_state(1, dtype=np.uint32)[0])


def _read_index(root: Path, *, index_name: str = "index.csv") -> list[TestRecord]:
    """Read a fixed-suite index, including pre-Scheme-2 aliases.

    ``validation_index.csv`` was used by an older release while the formal
    test suite uses ``index.csv``.  Keeping the filename explicit lets the
    migration utility canonicalize either file without touching instance CSVs.
    """
    path = root / index_name
    if not path.exists():
        return []
    out = []
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        for row in csv.DictReader(handle):
            out.append(TestRecord(
                instance_id=row["instance_id"],
                path=str(root / row["relative_path"]),
                scale=row["scale"],
                scenario=row["scenario"],
                generation_seed=int(row["generation_seed"]),
                target_load_ratio=float(row["target_load_ratio"]),
                due_tightness=row["due_tightness"],
                parameter_case_id=(row.get("parameter_case_id") or None),
                num_cells=int(row["num_cells"]) if row.get("num_cells") else None,
                num_stages=int(
                    row.get("S") or row.get("num_stages") or row.get("A")
                ) if (row.get("S") or row.get("num_stages") or row.get("A")) else None,
                num_robots=int(row["num_robots"]) if row.get("num_robots") else None,
                num_orders=int(row["num_orders"]) if row.get("num_orders") else None,
                relocation_multiplier=float(row.get("relocation_multiplier") or 1.0),
                worker_skill_density=(
                    float(row["worker_skill_density"])
                    if row.get("worker_skill_density") else None
                ),
                robot_capability_density=(
                    float(row["robot_capability_density"])
                    if row.get("robot_capability_density") else None
                ),
            ))
    return out


def _write_index(
    root: Path,
    records: list[TestRecord],
    *,
    index_name: str = "index.csv",
) -> None:
    path = root / index_name
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=TEST_INDEX_FIELDS)
        writer.writeheader()
        for record in sorted(records, key=lambda r: r.instance_id):
            inst = load_instance_csv(record.path)
            writer.writerow({
                "instance_id": record.instance_id,
                "relative_path": Path(record.path).relative_to(root).as_posix(),
                "scale": record.scale,
                "scenario": record.scenario,
                "generation_seed": record.generation_seed,
                "target_load_ratio": record.target_load_ratio,
                "due_tightness": record.due_tightness,
                "num_orders": inst.num_orders,
                "num_cells": inst.num_cells,
                "num_workers": inst.num_workers,
                "num_robots": inst.num_robots,
                "num_stages": inst.num_stages,
                "num_products": inst.num_products,
                "relocation_multiplier": inst.relocation_multiplier,
                "worker_skill_density": inst.worker_skill_density,
                "robot_capability_density": inst.robot_capability_density,
                "S": inst.num_stages,
                "M": inst.num_cells,
                # Deprecated alias for consumers of pre-Scheme-2 indexes.
                "A": inst.num_stages,
                "J": inst.num_orders,
                "H": inst.num_workers,
                "R": inst.num_robots,
                "V": inst.num_products,
                "parameter_case_id": record.parameter_case_id or "",
            })


def ensure_fixed_test_suite(
    cfg,
    *,
    root: str | Path,
    base_seed: int,
    scales,
    scenarios,
    load_ratios,
    due_tightness,
    instances_per_combination: int,
    prefix: str = "test",
    instance_parameter_table_path: str | Path | None = None,
    one_per_parameter_case: bool = False,
    relocation_multiplier: float = 1.0,
    worker_skill_density: float | None = None,
    robot_capability_density: float | None = None,
) -> tuple[TestRecord, ...]:
    """Materialize requested test cells once; existing files are authoritative."""
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    count = int(instances_per_combination)
    if count <= 0:
        raise ValueError("instances_per_combination must be positive")
    relocation_multiplier = float(relocation_multiplier)
    if relocation_multiplier < 0:
        raise ValueError("relocation_multiplier must be non-negative")
    if worker_skill_density is not None and not 0.0 < float(worker_skill_density) <= 1.0:
        raise ValueError("worker_skill_density must be in (0, 1]")
    if robot_capability_density is not None and not 0.0 < float(robot_capability_density) <= 1.0:
        raise ValueError("robot_capability_density must be in (0, 1]")
    generator = InstanceGenerator(cfg)
    existing = {r.instance_id: r for r in _read_index(root)}
    selected: list[TestRecord] = []
    combo = 0
    table = load_parameter_table(instance_parameter_table_path) if instance_parameter_table_path else None
    cases = (
        [(case_id, params) for case_id, params in table.items() if str(params["scale"]) in set(map(str, scales))]
        if table is not None else
        [(None, {"scale": scale}) for scale in scales]
    )
    if not cases:
        raise ValueError("test parameter table has no cases matching requested scales")
    for case_index, (case_id, case_params) in enumerate(cases):
        scale = str(case_params["scale"])
        factor_cells = (
            [
                (
                    tuple(scenarios)[case_index % len(tuple(scenarios))],
                    tuple(load_ratios)[case_index % len(tuple(load_ratios))],
                    tuple(due_tightness)[case_index % len(tuple(due_tightness))],
                    0,
                )
            ]
            if one_per_parameter_case else
            [
                (scenario, rho, due, rep)
                for scenario in scenarios
                for rho in load_ratios
                for due in due_tightness
                for rep in range(count)
            ]
        )
        for scenario, rho, due, rep in factor_cells:
            seed = _seed(base_seed, combo, rep)
            case_label = "base" if case_id is None else str(case_id)
            iid = (
                f"{prefix}_{case_label}_{scenario}_rho{int(round(float(rho)*100)):03d}_"
                f"{due}_{rep:03d}"
                + (f"_rm{relocation_multiplier:g}" if abs(relocation_multiplier - 1.0) > 1e-12 else "")
                + (
                    f"_wsd{int(round(float(worker_skill_density) * 100)):03d}"
                    if worker_skill_density is not None else ""
                )
                + (
                    f"_rcd{int(round(float(robot_capability_density) * 100)):03d}"
                    if robot_capability_density is not None else ""
                )
            )
            path = root / f"{iid}.csv"
            if path.exists():
                inst = load_instance_csv(path)
                expected = (str(scale), str(scenario), round(float(rho), 8), str(due))
                actual = (
                    inst.scale, inst.scenario,
                    round(float(inst.target_load_ratio), 8), inst.due_tightness,
                )
                if actual != expected:
                    raise ValueError(
                        f"existing test file {path} does not match requested cell: "
                        f"expected={expected}, actual={actual}"
                    )
                if (
                    abs(float(inst.relocation_multiplier) - relocation_multiplier) > 1e-12
                    or (worker_skill_density is not None and abs(
                        float(inst.worker_skill_density) - float(worker_skill_density)
                    ) > 1e-12)
                    or (robot_capability_density is not None and abs(
                        float(inst.robot_capability_density) - float(robot_capability_density)
                    ) > 1e-12)
                ):
                    raise ValueError(f"existing test file {path} has different sensitivity factors")
            else:
                params = None if case_id is None else dict(case_params)
                inst = generator.sample(
                    scale=str(scale), scenario=str(scenario), seed=seed,
                    load_ratio=float(rho), due_tightness=str(due), instance_id=iid,
                    instance_parameters=params,
                    relocation_multiplier=relocation_multiplier,
                    worker_skill_density=worker_skill_density,
                    robot_capability_density=robot_capability_density,
                )
                save_instance_csv(inst, path)
            record = TestRecord(
                instance_id=inst.instance_id,
                path=str(path),
                scale=inst.scale,
                scenario=inst.scenario,
                generation_seed=seed,
                target_load_ratio=float(inst.target_load_ratio),
                due_tightness=inst.due_tightness,
                parameter_case_id=(None if case_id is None else str(case_id)),
                num_cells=inst.num_cells,
                num_stages=inst.num_stages,
                num_robots=inst.num_robots,
                num_orders=inst.num_orders,
                relocation_multiplier=float(inst.relocation_multiplier),
                worker_skill_density=float(inst.worker_skill_density),
                robot_capability_density=float(inst.robot_capability_density),
            )
            existing[iid] = record
            selected.append(record)
            combo += 1
    _write_index(root, list(existing.values()))
    return tuple(selected)


def migrate_index_schema_without_regeneration(
    root: str | Path,
    *,
    index_name: str = "index.csv",
) -> tuple[TestRecord, ...]:
    """Rewrite one fixed-suite index to the canonical schema only.

    Existing instance CSV bytes are hashed before and after the rewrite.  A
    mismatch is treated as an error so a metadata migration can never silently
    regenerate or alter the fixed benchmark itself.
    """
    import hashlib

    root = Path(root)
    records = _read_index(root, index_name=index_name)
    if not records:
        raise FileNotFoundError(root / index_name)

    csv_paths = sorted(
        path for path in root.glob("*.csv") if path.name != index_name
    )

    def digest(path: Path) -> str:
        return hashlib.sha256(path.read_bytes()).hexdigest()

    before = {path.name: digest(path) for path in csv_paths}
    _write_index(root, records, index_name=index_name)
    after = {path.name: digest(path) for path in csv_paths}
    if before != after:
        raise RuntimeError(
            f"fixed instance CSV contents changed while migrating {root / index_name}"
        )
    return tuple(records)


def load_test_records(root: str | Path, *, scales=None, scenarios=None) -> tuple[TestRecord, ...]:
    root = Path(root)
    records = _read_index(root)
    if scales is not None:
        allowed = set(scales)
        records = [r for r in records if r.scale in allowed]
    if scenarios is not None:
        allowed = set(scenarios)
        records = [r for r in records if r.scenario in allowed]
    return tuple(records)


